func TestMaxFileBytesWindowsRatherThanStrips(t *testing.T) {
	// The bug this pins: max_file_bytes decided whether content was attached AT
	// ALL, so a file one byte over the cap was reviewed from its diff while a
	// file one byte under it got a full window. The cap bounds what a run
	// holds; it must not decide how much of a file is understood.
	cfg := baseConfig()
	cfg.Review.MaxFileBytes = 4096

	// One edit in the middle of a long file: the shape a window exists for.
	// diffFor always adds from line 1, which would leave nothing to elide above
	// the change.
	const changedLine = 500
	files := diff.Files{{Path: "big.go", Kind: diff.ChangeModified, Hunks: []diff.Hunk{{
		NewStart: changedLine,
		NewLines: 1,
		Lines:    []diff.Line{{Kind: diff.LineAdded, NewLine: changedLine, Content: "edited"}},
	}}}}

	var body strings.Builder
	for i := 1; i <= 4000; i++ {
		fmt.Fprintf(&body, "line %d of a file well past the byte cap\n", i)
	}
	if body.Len() <= cfg.Review.MaxFileBytes {
		t.Fatalf("body is %d bytes, want it over the %d-byte cap", body.Len(), cfg.Review.MaxFileBytes)
	}
	fetch := func(context.Context, string) ([]byte, error) { return []byte(body.String()), nil }

	plan, err := Assemble(context.Background(), cfg, files, fetch)
	if err != nil {
		t.Fatalf("Assemble: %v", err)
	}

	entry := plan.Batches[0].Entries[0]
	if !entry.HasContent() {
		t.Fatalf("an oversized file must be windowed, not stripped; degraded=%+v", plan.Degraded)
	}
	if !entry.Truncated || entry.ContextLines <= 0 {
		t.Fatalf("content should be marked as a window of known width, got truncated=%v context=%d",
			entry.Truncated, entry.ContextLines)
	}
	// The cap still binds, or it would not be a cap, and it binds on the file's
	// own bytes, the same quantity it was compared against to reject the whole
	// file. Held against the NUMBERED text instead, the two call sites measured
	// different things and a window came out larger than the file it was cut
	// from.
	if got := sourceBytes(t, entry.Content); got > cfg.Review.MaxFileBytes {
		t.Errorf("the window retains %d bytes of the file, over the %d-byte cap", got, cfg.Review.MaxFileBytes)
	}
	// Reviewed with reduced context is neither "not reviewed" nor "reviewed in
	// full": it belongs in Windowed, and nowhere else.
	if len(plan.Skipped) != 0 || len(plan.Degraded) != 0 {
		t.Errorf("skipped=%+v degraded=%+v, want both empty for a file reviewed with a window", plan.Skipped, plan.Degraded)
	}
	if len(plan.Windowed) != 1 || !strings.HasPrefix(plan.Windowed[0].Reason, ReasonTooLarge) {
		t.Errorf("windowed = %+v, want one entry naming %q", plan.Windowed, ReasonTooLarge)
	}
	if !strings.Contains(plan.Windowed[0].Reason, fmt.Sprint(entry.ContextLines)) {
		t.Errorf("reason %q should state the %d-line width it settled on", plan.Windowed[0].Reason, entry.ContextLines)
	}
}

func TestMaxFileBytesFallsBackToDiffOnlyWhenNoWindowFits(t *testing.T) {
	// A cap too small for even one line of context: there is no honest window
	// left, so the file drops to diff-only. And that must be recorded, since a
	// contentless entry is otherwise indistinguishable from a fully attached one.
	cfg := baseConfig()
	cfg.Review.MaxFileBytes = 10

	files := diffFor(t, "a.go", 2)
	fetch := func(context.Context, string) ([]byte, error) {
		return []byte(strings.Repeat("x", 100) + "\n"), nil
	}

	plan, err := Assemble(context.Background(), cfg, files, fetch)
	if err != nil {
		t.Fatalf("Assemble: %v", err)
	}
	if plan.Batches[0].Entries[0].HasContent() {
		t.Error("content that cannot be windowed under the cap should not be attached")
	}
	if len(plan.Degraded) != 1 || !strings.HasPrefix(plan.Degraded[0].Reason, ReasonTooLarge) {
		t.Fatalf("degraded = %+v, want one entry naming %q", plan.Degraded, ReasonTooLarge)
	}
	if !strings.Contains(plan.Degraded[0].Reason, "diff alone") {
		t.Errorf("reason %q should say the file was reviewed from the diff alone", plan.Degraded[0].Reason)
	}
	if len(plan.Skipped) != 0 {
		t.Errorf("skipped = %+v, want empty for a file that was reviewed", plan.Skipped)
	}
	if len(plan.Windowed) != 0 {
		t.Errorf("windowed = %+v, want empty: nothing was windowed", plan.Windowed)
	}
}

