func TestBatchingRespectsFileCount(t *testing.T) {
	cfg := baseConfig()
	cfg.Review.MaxFilesPerRequest = 2

	var files diff.Files
	for i := range 5 {
		files = append(files, diffFor(t, fmt.Sprintf("f%d.go", i), 1)...)
	}

	plan, err := Assemble(context.Background(), cfg, files, nil)
	if err != nil {
		t.Fatalf("Assemble: %v", err)
	}
	if len(plan.Batches) != 3 {
		t.Fatalf("batches = %d, want 3 for 5 files at 2 per request", len(plan.Batches))
	}
	for i, b := range plan.Batches {
		if len(b.Entries) > 2 {
			t.Errorf("batch %d has %d entries, want at most 2", i, len(b.Entries))
		}
	}
	if plan.Files() != 5 {
		t.Errorf("total files = %d, want 5: batching must not lose files", plan.Files())
	}
}

func TestBatchingRespectsTokenBudget(t *testing.T) {
	cfg := baseConfig()
	cfg.Review.MaxFilesPerRequest = 100
	cfg.Review.TokenBudgetPerRequest = 400

	var files diff.Files
	for i := range 6 {
		files = append(files, diffFor(t, fmt.Sprintf("f%d.go", i), 30)...)
	}

	plan, err := Assemble(context.Background(), cfg, files, nil)
	if err != nil {
		t.Fatalf("Assemble: %v", err)
	}
	if len(plan.Batches) < 2 {
		t.Fatalf("batches = %d, want the budget to force a split", len(plan.Batches))
	}
	for i, b := range plan.Batches {
		if len(b.Entries) > 1 && b.Tokens > cfg.Review.TokenBudgetPerRequest {
			t.Errorf("batch %d has %d tokens, over the %d budget", i, b.Tokens, cfg.Review.TokenBudgetPerRequest)
		}
	}
}

