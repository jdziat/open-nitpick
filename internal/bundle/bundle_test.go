// diffFor builds a one-file diff adding n lines to path, for shaping tests.
func diffFor(t *testing.T, path string, n int) diff.Files {
	t.Helper()

	var b strings.Builder
	fmt.Fprintf(&b, "diff --git a/%s b/%s\n--- a/%s\n+++ b/%s\n@@ -1,0 +1,%d @@\n", path, path, path, path, n)
	for i := 1; i <= n; i++ {
		fmt.Fprintf(&b, "+line %d\n", i)
	}

	files, err := diff.Parse([]byte(b.String()))
	if err != nil {
		t.Fatalf("parse generated diff: %v", err)
	}
	return files
}

func baseConfig() *config.Config {
	cfg := config.Defaults()
	cfg.Models.Default = config.ModelSpec{Provider: "openai", Model: "gpt-4o"}
	return cfg
}

func TestAssembleSkipsIgnoredFiles(t *testing.T) {
	cfg := baseConfig()
	files := diffFor(t, "vendor/x/y.go", 2)

	plan, err := Assemble(context.Background(), cfg, files, nil)
	if err != nil {
		t.Fatalf("Assemble: %v", err)
	}
	if plan.Files() != 0 {
		t.Errorf("files = %d, want 0", plan.Files())
	}
	if len(plan.Skipped) != 1 || plan.Skipped[0].Reason != ReasonIgnored {
		t.Errorf("skipped = %+v, want one ignored entry", plan.Skipped)
	}
}

func TestAssembleSkipsDeletedAndBinary(t *testing.T) {
	const d = `diff --git a/gone.go b/gone.go
deleted file mode 100644
--- a/gone.go
+++ /dev/null
@@ -1,1 +0,0 @@
-package main
diff --git a/img.bin b/img.bin
index 1..2 100644
Binary files a/img.bin and b/img.bin differ
`
	files, err := diff.Parse([]byte(d))
	if err != nil {
		t.Fatalf("parse: %v", err)
	}

	plan, err := Assemble(context.Background(), baseConfig(), files, nil)
	if err != nil {
		t.Fatalf("Assemble: %v", err)
	}
	if plan.Files() != 0 {
		t.Errorf("files = %d, want 0", plan.Files())
	}

	reasons := map[string]string{}
	for _, s := range plan.Skipped {
		reasons[s.Path] = s.Reason
	}
	if reasons["gone.go"] != ReasonDeleted {
		t.Errorf("gone.go reason = %q, want %q", reasons["gone.go"], ReasonDeleted)
	}
	if reasons["img.bin"] != ReasonBinary {
		t.Errorf("img.bin reason = %q, want %q", reasons["img.bin"], ReasonBinary)
	}
}

