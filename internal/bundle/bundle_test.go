func TestAssembleAttachesContent(t *testing.T) {
	files := diffFor(t, "a.go", 2)
	fetch := func(context.Context, string) ([]byte, error) {
		return []byte("package a\n\nfunc F() {}\n"), nil
	}

	plan, err := Assemble(context.Background(), baseConfig(), files, fetch)
	if err != nil {
		t.Fatalf("Assemble: %v", err)
	}

	entry := plan.Batches[0].Entries[0]
	if !entry.HasContent() {
		t.Fatal("full file content should be attached")
	}

	rendered := Render(entry)
	if !strings.Contains(rendered, "Full file after the change") {
		t.Error("rendered entry should include the full file section")
	}
	// Numbered so the model can cite lines outside the diff.
	if !strings.Contains(rendered, "     1  package a") {
		t.Errorf("full file should be line-numbered:\n%s", rendered)
	}
}

func TestAssembleDegradesWhenContentUnavailable(t *testing.T) {
	// A fetch failure must not lose the file; the diff is still reviewable.
	files := diffFor(t, "a.go", 2)
	fetch := func(context.Context, string) ([]byte, error) {
		return nil, vcs.ErrNotFound
	}

	plan, err := Assemble(context.Background(), baseConfig(), files, fetch)
	if err != nil {
		t.Fatalf("Assemble: %v", err)
	}
	if plan.Files() != 1 {
		t.Fatalf("files = %d, want the file to still be reviewed", plan.Files())
	}
	if plan.Batches[0].Entries[0].HasContent() {
		t.Error("content should be empty when the fetch failed")
	}
	if len(plan.Degraded) != 1 || plan.Degraded[0].Reason != ReasonUnavailable {
		t.Errorf("degraded = %+v, want the unavailable reason recorded", plan.Degraded)
	}
	// The file WAS reviewed, so it must not also appear as skipped: the
	// renderer lists Skipped under "Files not reviewed".
	if len(plan.Skipped) != 0 {
		t.Errorf("skipped = %+v, want empty for a file that was reviewed", plan.Skipped)
	}
}

