func TestGeneratedFilesDoNotSpendTheFileLimit(t *testing.T) {
	// review.max_files bounds how many files are REVIEWED. A generated file is
	// only recognisable once its content has been read, and counting it against
	// the limit before that refused reviewable files behind it for a limit
	// nothing reviewed had reached: six files at max_files=3 whose first three
	// were generated reviewed NOTHING, and reported success.
	cfg := baseConfig()
	cfg.Review.MaxFiles = 3

	var files diff.Files
	for i := range 6 {
		files = append(files, diffFor(t, fmt.Sprintf("f%d.go", i), 1)...)
	}

	generated := map[string]bool{"f0.go": true, "f1.go": true, "f2.go": true}
	fetch := func(_ context.Context, path string) ([]byte, error) {
		if generated[path] {
			return []byte("// Code generated by probe. DO NOT EDIT.\npackage x\n"), nil
		}
		return []byte("package x\n"), nil
	}

	plan, err := Assemble(context.Background(), cfg, files, fetch)
	if err != nil {
		t.Fatalf("Assemble: %v", err)
	}

	if plan.Files() != 3 {
		t.Errorf("reviewed %d files, want the %d the limit allows: generated files must not spend slots", plan.Files(), cfg.Review.MaxFiles)
	}

	reasons := map[string]string{}
	for _, s := range plan.Skipped {
		reasons[s.Path] = s.Reason
	}
	for path := range generated {
		if reasons[path] != ReasonGenerated {
			t.Errorf("%s skipped for %q, want %q", path, reasons[path], ReasonGenerated)
		}
	}
	for _, path := range []string{"f3.go", "f4.go", "f5.go"} {
		if reasons[path] != "" {
			t.Errorf("%s was skipped for %q, but the file limit was never reached by anything reviewed", path, reasons[path])
		}
	}
}

