// diffFor builds a one-file diff adding n lines to path, for shaping tests.
func diffFor(t *testing.T, path string, n int) diff.Files {
	t.Helper()

	var b strings.Builder
	fmt.Fprintf(&b, "diff --git a/%s b/%s\n--- a/%s\n+++ b/%s\n@@ -1,0 +1,%d @@\n", path, path, path, path, n)
	for i := 1; i <= n; i++ {
		fmt.Fprintf(&b, "+line %d\n", i)
	}

	files, err := diff.Parse([]byte(b.String()))
	if err != nil {
		t.Fatalf("parse generated diff: %v", err)
	}
	return files
}

