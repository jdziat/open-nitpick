func TestLargeFileContentIsWindowed(t *testing.T) {
	cfg := baseConfig()
	cfg.Review.TokenBudgetPerRequest = 900

	// A small change in a large file: the window should keep the changed
	// region and elide the rest rather than dropping context entirely.
	const changedLine = 3
	files := diffFor(t, "big.go", changedLine)

	var body strings.Builder
	for i := 1; i <= 2000; i++ {
		fmt.Fprintf(&body, "line %d of a very long file\n", i)
	}
	fetch := func(context.Context, string) ([]byte, error) { return []byte(body.String()), nil }

	plan, err := Assemble(context.Background(), cfg, files, fetch)
	if err != nil {
		t.Fatalf("Assemble: %v", err)
	}

	entry := plan.Batches[0].Entries[0]
	if !entry.Truncated {
		t.Fatalf("content should have been windowed; tokens=%d budget=%d hasContent=%v",
			entry.Tokens, cfg.Review.TokenBudgetPerRequest, entry.HasContent())
	}
	if !strings.Contains(entry.Content, "unchanged lines omitted") {
		t.Error("windowed content should mark what it elided")
	}
	// The region around the change survives.
	if !strings.Contains(entry.Content, "line 1 of a very long file") {
		t.Error("window should keep lines around the change")
	}
	if strings.Contains(entry.Content, "line 1500 of a very long file") {
		t.Error("window should elide distant lines")
	}

	rendered := Render(entry)
	if strings.Count(rendered, "unchanged lines omitted") == 0 {
		t.Error("rendered entry should show the elision markers")
	}
	// Windowed content is pre-numbered; numbering it again would produce
	// line numbers that do not match the file.
	if strings.Contains(rendered, "     1       1  line 1") {
		t.Error("windowed content was numbered twice")
	}
}

