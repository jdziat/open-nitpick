func TestIsGeneratedOnlyScansTheTop(t *testing.T) {
	// An ordinary comment deep in a file must not suppress its review.
	body := strings.Repeat("// ordinary code\n", 40) + "// DO NOT EDIT this by hand\n"
	if isGenerated(body) {
		t.Error("a marker far into the file should not count as generated")
	}
	if !isGenerated("// Code generated by tool. DO NOT EDIT.\npackage x\n") {
		t.Error("a leading marker should count as generated")
	}
}

