func TestFullSourcePrefetchOverlapsReadsWithinFileAndWorkerLimits(t *testing.T) {
	for _, limit := range []int{2, 8} {
		t.Run(fmt.Sprint(limit), func(t *testing.T) {
			cfg := baseConfig()
			cfg.Review.MaxFiles = limit
			cfg.Review.IncludeFullFiles = true
			cfg.Review.RelatedContext = false
			cfg.Review.Ignore = append(cfg.Review.Ignore, "blocked.txt")
			files := diffFor(t, "blocked.txt", 1)
			files = append(files, diffFor(t, "deleted.txt", 1)...)
			files[1].Kind = diff.ChangeDeleted
			files = append(files, diffFor(t, "binary.txt", 1)...)
			files[2].Binary = true
			var want []string
			for i := range limit + 1 {
				name := fmt.Sprintf("file-%02d.txt", i)
				files = append(files, diffFor(t, name, 1)...)
				if i < limit {
					want = append(want, name)
				}
			}
			ctx, cancel := context.WithTimeout(t.Context(), 5*time.Second)
			defer cancel()
			started := make(chan string, limit+1)
			release := make(chan struct{}, limit)
			defer close(release)
			var active, peak atomic.Int64
			var mu sync.Mutex
			var reads []string
			fetch := func(ctx context.Context, name string) ([]byte, error) {
				mu.Lock()
				reads = append(reads, name)
				mu.Unlock()
				n := active.Add(1)
				defer active.Add(-1)
				for old := peak.Load(); n > old; old = peak.Load() {
					if peak.CompareAndSwap(old, n) {
						break
					}
				}
				started <- name
				select {
				case <-release:
					return []byte(name + "\n"), nil
				case <-ctx.Done():
					return nil, ctx.Err()
				}
			}
			type result struct {
				Plan *Plan
				Err  error
			}
			done := make(chan result, 1)
			go func() { p, e := Assemble(ctx, cfg, files, fetch); done <- result{p, e} }()
			for range min(limit, 4) {
				select {
				case <-started:
				case <-ctx.Done():
					t.Fatal("source reads stayed serial")
				}
			}
			select {
			case path := <-started:
				t.Fatalf("read %s exceeded the %d-reader window", path, min(limit, 4))
			case <-time.After(50 * time.Millisecond):
			}
			for range limit {
				release <- struct{}{}
			}
			got := <-done
			if got.Err != nil {
				t.Fatal(got.Err)
			}
			if peak.Load() > 4 || active.Load() != 0 {
				t.Fatalf("unbounded or undrained workers: peak=%d active=%d", peak.Load(), active.Load())
			}
			var paths []string
			for _, batch := range got.Plan.Batches {
				paths = append(paths, batch.Paths()...)
				for _, entry := range batch.Entries {
					if entry.Content != entry.File.Path+"\n" {
						t.Fatalf("source assigned to wrong file: path=%s content=%q", entry.File.Path, entry.Content)
					}
				}
			}
			if !slices.Equal(paths, want) {
				t.Fatalf("ordered selection changed: got=%v want=%v", paths, want)
			}
			slices.Sort(reads)
			if !slices.Equal(reads, want) {
				t.Fatalf("ignored or budget-omitted file read: got=%v want=%v", reads, want)
			}
		})
	}
}

func TestFullSourcePrefetchRefillsSlotsAfterGeneratedFiles(t *testing.T) {
	cfg := baseConfig()
	cfg.Review.MaxFiles = 2
	cfg.Review.IncludeFullFiles = true
	cfg.Review.RelatedContext = false
	cfg.Review.SkipGenerated = true
	var files diff.Files
	for _, name := range []string{"generated.go", "one.txt", "two.txt", "over-limit.txt"} {
		files = append(files, diffFor(t, name, 1)...)
	}
	var mu sync.Mutex
	var reads []string
	plan, err := Assemble(t.Context(), cfg, files, func(_ context.Context, name string) ([]byte, error) {
		mu.Lock()
		reads = append(reads, name)
		mu.Unlock()
		if name == "generated.go" {
			return []byte("// Code generated by test. DO NOT EDIT.\npackage sample\n"), nil
		}
		return []byte("line 1\n"), nil
	})
	if err != nil {
		t.Fatal(err)
	}
	slices.Sort(reads)
	if plan.Files() != 2 || !slices.Equal(reads, []string{"generated.go", "one.txt", "two.txt"}) {
		t.Fatalf("generated skip changed budget or reads: files=%d reads=%v", plan.Files(), reads)
	}
}

func TestFullSourcePrefetchDrainsAllReadsWhenCancelled(t *testing.T) {
	cfg := baseConfig()
	cfg.Review.MaxFiles = 2
	cfg.Review.IncludeFullFiles = true
	cfg.Review.RelatedContext = false
	files := append(diffFor(t, "one.txt", 1), diffFor(t, "two.txt", 1)...)
	ctx, cancel := context.WithTimeout(t.Context(), 5*time.Second)
	defer cancel()
	started := make(chan struct{}, 2)
	waiting := make(chan struct{})
	release := make(chan struct{})
	defer close(release)
	var active atomic.Int64
	done := make(chan error, 1)
	go func() {
		_, err := Assemble(ctx, cfg, files, func(ctx context.Context, name string) ([]byte, error) {
			active.Add(1)
			defer active.Add(-1)
			started <- struct{}{}
			<-ctx.Done()
			if name == "two.txt" {
				close(waiting)
				<-release
			}
			return nil, ctx.Err()
		})
		done <- err
	}()
	for range 2 {
		select {
		case <-started:
		case <-ctx.Done():
			t.Fatal("cancellation control did not start two reads")
		}
	}
	cancel()
	<-waiting
	select {
	case err := <-done:
		t.Fatalf("assembly returned before the cancelled reader drained: %v", err)
	case <-time.After(50 * time.Millisecond):
	}
	release <- struct{}{}
	if err := <-done; !errors.Is(err, context.Canceled) {
		t.Fatalf("cancelled assembly error=%v", err)
	}
	if active.Load() != 0 {
		t.Fatal("assembly returned while source reads were still running")
	}
}

func TestFullSourcePrefetchDoesNoIOForDiffOnlyOrExcludedFiles(t *testing.T) {
	for _, mode := range []string{"diff only", "ignored", "deleted", "binary", "no changes"} {
		t.Run(mode, func(t *testing.T) {
			cfg := baseConfig()
			cfg.Review.IncludeFullFiles = true
			cfg.Review.RelatedContext = false
			files := diffFor(t, "one.txt", 1)
			wantFiles := 0
			switch mode {
			case "diff only":
				cfg.Review.IncludeFullFiles = false
				wantFiles = 1
			case "ignored":
				cfg.Review.Ignore = append(cfg.Review.Ignore, "one.txt")
			case "deleted":
				files[0].Kind = diff.ChangeDeleted
			case "binary":
				files[0].Binary = true
			case "no changes":
				files = diffFor(t, "one.txt", 0)
			}
			var reads atomic.Int64
			plan, err := Assemble(t.Context(), cfg, files, func(context.Context, string) ([]byte, error) { reads.Add(1); return []byte("line 1\n"), nil })
			if err != nil {
				t.Fatal(err)
			}
			if reads.Load() != 0 || plan.Files() != wantFiles || len(plan.Skipped) != 1-wantFiles {
				t.Fatalf("silence lacks its expected scope: reads=%d files=%d skips=%v", reads.Load(), plan.Files(), plan.Skipped)
			}
		})
	}
}

func TestFullSourcePrefetchPreservesFetchErrorsAndDiffOnlyFallback(t *testing.T) {
	cfg := baseConfig()
	cfg.Review.IncludeFullFiles = true
	cfg.Review.RelatedContext = false
	files := append(diffFor(t, "bad.txt", 1), diffFor(t, "good.txt", 1)...)
	var reads atomic.Int64
	plan, err := Assemble(t.Context(), cfg, files, func(_ context.Context, name string) ([]byte, error) {
		reads.Add(1)
		if name == "bad.txt" {
			return nil, errors.New("provider unavailable")
		}
		return []byte("line 1\n"), nil
	})
	if err != nil {
		t.Fatal(err)
	}
	if reads.Load() != 2 || plan.Files() != 2 || len(plan.Degraded) != 1 || plan.Degraded[0].Path != "bad.txt" || !strings.Contains(plan.Degraded[0].Reason, "provider unavailable") {
		t.Fatalf("fetch error lost or repeated: reads=%d files=%d degraded=%v", reads.Load(), plan.Files(), plan.Degraded)
	}
	var content []string
	for _, batch := range plan.Batches {
		for _, entry := range batch.Entries {
			content = append(content, entry.Content)
		}
	}
	if len(content) != 2 || content[0] != "" || content[1] == "" {
		t.Fatalf("diff-only fallback changed: %q", content)
	}
}
