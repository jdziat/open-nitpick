// Status describes selected check execution, never overall correctness.
type Status string

const (
	// Passed means the selected command exited successfully under this policy.
	Passed Status = "checks passed"
	// Failed means the selected command ran and failed.
	Failed Status = "checks failed"
	// Unavailable means the result cannot establish that selected checks ran.
	Unavailable Status = "unavailable/incomplete"
)

// Check selects one fixed tool profile and a repository-relative Go package.
type Check struct {
	Kind    string `json:"kind"`
	Package string `json:"package"`
}

// Validate refuses commands outside the fixed check profiles.
func (c Check) Validate() error { return c.validate() }

func (c Check) validate() error {
	if c.Kind != "go_build" && c.Kind != "go_test" {
		return errors.New("unsupported trusted command profile")
	}
	if c.Package != "." && (c.Package == "" || path.Clean(c.Package) != c.Package || strings.HasPrefix(c.Package, "/") || strings.HasPrefix(c.Package, "../") || strings.Contains(c.Package, "..") || !regexp.MustCompile(`^[a-zA-Z0-9_./-]+$`).MatchString(c.Package)) {
		return errors.New("invalid package scope")
	}
	return nil
}

// Policy fixes the runtime and image before untrusted code is admitted.
// Runtime defaults to gVisor. runc shares the host kernel, so it is accepted
// only for the hand-picked examples declared by TrustedCorpus.
type Policy struct {
	Image          string `json:"image"`
	Runtime        string `json:"runtime"`
	TrustedCorpus  bool   `json:"trusted_corpus"`
	RiskAccepted   bool   `json:"risk_accepted"`
	TimeoutSeconds int    `json:"timeout_seconds"`
	MemoryMiB      int    `json:"memory_mib"`
	CPUs           int    `json:"cpus"`
	Pids           int    `json:"pids"`
	DiskMiB        int    `json:"disk_mib"`
	MaxOutputBytes int    `json:"max_output_bytes"`
}

// Result is generated by the parent from runtime outcome, never by parsing
// a file or success marker writable by the code being checked.
type Result struct {
	Signature       string `json:"signature"`
	JobID           string `json:"job_id"`
	Head            string `json:"head"`
	SnapshotSHA256  string `json:"snapshot_sha256"`
	PolicySHA256    string `json:"policy_sha256"`
	Check           Check  `json:"check"`
	Status          Status `json:"status"`
	Runtime         string `json:"runtime"`
	Reason          string `json:"reason,omitempty"`
	ExitCode        int    `json:"exit_code"`
	DurationMS      int64  `json:"duration_ms"`
	OutputSHA256    string `json:"output_sha256"`
	OutputTruncated bool   `json:"output_truncated"`
	Output          []byte `json:"-"`
}

type commandRunner func(context.Context, []string, io.Writer) (int, error)

// Runner executes checks through a separately controlled Docker daemon, under
// gVisor or, for a corpus the operator declared trusted, under runc.
type Runner struct {
	policy  Policy
	command commandRunner
	key     [32]byte
}

// NewRunner rejects absent risk acceptance, mutable images, missing limits and
// a shared-kernel runtime without a trusted-corpus declaration.
func NewRunner(policy Policy) (*Runner, error) {
	if policy.Runtime == "" {
		policy.Runtime = "runsc"
	}
	if err := ValidatePolicy(policy); err != nil {
		return nil, err
	}
	binary, err := exec.LookPath("docker")
	if err != nil {
		return nil, fmt.Errorf("execution control client: %w", err)
	}
	runner := &Runner{policy: policy}
	if _, err := rand.Read(runner.key[:]); err != nil {
		return nil, fmt.Errorf("execution result authentication: %w", err)
	}
	runner.command = func(ctx context.Context, args []string, out io.Writer) (int, error) {
		cmd := exec.CommandContext(ctx, binary, args...)
		cmd.Env = []string{"PATH=/usr/bin:/bin"}
		cmd.Stdout, cmd.Stderr = out, out
		cmd.WaitDelay = 2 * time.Second
		err := cmd.Run()
		if err == nil {
			return 0, nil
		}
		var exit *exec.ExitError
		if errors.As(err, &exit) {
			return exit.ExitCode(), nil
		}
		return -1, err
	}
	return runner, nil
}

// ValidatePolicy checks an operator policy without requiring Docker on this host.
func ValidatePolicy(policy Policy) error {
	if !policy.RiskAccepted {
		return errors.New("execution backend residual risk has not been accepted")
	}
	if policy.Runtime == "" {
		policy.Runtime = "runsc"
	}
	switch {
	case policy.Runtime != "runsc" && policy.Runtime != "runc":
		return errors.New("execution runtime must be runsc or runc")
	case policy.Runtime == "runc" && !policy.TrustedCorpus:
		return errors.New("runc shares the host kernel and requires a declared trusted corpus")
	}
	if !regexp.MustCompile(`^([a-zA-Z0-9][a-zA-Z0-9./:_-]*@)?sha256:[a-f0-9]{64}$`).MatchString(policy.Image) {
		return errors.New("execution requires an image pinned by sha256 digest")
	}
	if policy.TimeoutSeconds < 1 || policy.TimeoutSeconds > 600 || policy.MemoryMiB < 128 || policy.MemoryMiB > 8192 || policy.CPUs < 1 || policy.CPUs > 8 || policy.Pids < 16 || policy.Pids > 512 || policy.DiskMiB < 16 || policy.DiskMiB > 2048 || policy.MaxOutputBytes < 1024 || policy.MaxOutputBytes > 1<<20 {
		return errors.New("execution limits are absent or outside supported bounds")
	}
	return nil
}

type cappedOutput struct {
	data      []byte
	limit     int
	truncated bool
}

func (b *cappedOutput) Write(p []byte) (int, error) {
	count := len(p)
	remaining := b.limit - len(b.data)
	if len(p) > remaining {
		p = p[:remaining]
		b.truncated = true
	}
	b.data = append(b.data, p...)
	return count, nil
}

// Run admits one immutable archive and one trusted check, then destroys its
// container even on cancellation. Cleanup failure invalidates a passing exit.
func (r *Runner) Run(ctx context.Context, snapshot Snapshot, check Check) (result Result) {
	started := time.Now()
	raw, _ := json.Marshal(struct {
		Policy Policy
		Check  Check
	}{r.policy, check})
	policyHash := sha256.Sum256(raw)
	result = Result{Head: snapshot.Head, SnapshotSHA256: snapshot.SHA256, PolicySHA256: hex.EncodeToString(policyHash[:]), Check: check, Status: Unavailable, Runtime: r.policy.Runtime, ExitCode: -1}
	defer func() { result.Signature = r.signature(result) }()
	if err := validateSnapshot(snapshot); err != nil {
		result.Reason = err.Error()
		return result
	}
	if err := check.validate(); err != nil {
		result.Reason = err.Error()
		return result
	}
	var nonce [16]byte
	if _, err := rand.Read(nonce[:]); err != nil {
		result.Reason = "job identity unavailable"
		return result
	}
	result.JobID = "nitpick-" + hex.EncodeToString(nonce[:])
	dir, err := os.MkdirTemp("", "nitpick-execution-")
	if err != nil {
		result.Reason = "snapshot staging unavailable"
		return result
	}
	defer func() { _ = os.RemoveAll(dir) }()
	archive := filepath.Join(dir, "snapshot.tar")
	if err := os.WriteFile(archive, snapshot.Archive, 0444); err != nil {
		result.Reason = "snapshot staging failed"
		return result
	}
	ctx, cancel := context.WithTimeout(ctx, time.Duration(r.policy.TimeoutSeconds)*time.Second)
	defer cancel()
	output := &cappedOutput{limit: r.policy.MaxOutputBytes}
	args := []string{"run", "--name", result.JobID, "--runtime=" + r.policy.Runtime, "--pull=never", "--network=none", "--read-only", "--cap-drop=ALL", "--security-opt=no-new-privileges", "--user=65532:65532", "--log-driver=none", "--shm-size=16m", "--ulimit=nofile=1024:1024", "--ulimit=core=0:0",
		fmt.Sprintf("--cpus=%d", r.policy.CPUs), fmt.Sprintf("--memory=%dm", r.policy.MemoryMiB), fmt.Sprintf("--memory-swap=%dm", r.policy.MemoryMiB), fmt.Sprintf("--pids-limit=%d", r.policy.Pids),
		fmt.Sprintf("--tmpfs=/work:rw,nosuid,nodev,noexec,size=%dm,uid=65532,gid=65532", r.policy.DiskMiB), fmt.Sprintf("--tmpfs=/tmp:rw,nosuid,nodev,exec,size=%dm,uid=65532,gid=65532", r.policy.DiskMiB),
		"--mount=type=bind,src=" + archive + ",dst=/input/snapshot.tar,readonly",
		"--env=GOTOOLCHAIN=local", "--env=GOPROXY=off", "--env=GOSUMDB=off", "--env=GOCACHE=/tmp/go-cache", "--env=GOPATH=/tmp/go-path", "--env=GOMODCACHE=/opt/gomod", "--env=CGO_ENABLED=0",
		"--entrypoint=/usr/local/bin/nitpick-checker", r.policy.Image, "-head", snapshot.Head, "-sha256", snapshot.SHA256, "-kind", check.Kind, "-package", check.Package}
	exit, runErr := r.command(ctx, args, output)
	// Read before cleanup: the deadline answers whether the check itself ran
	// out of time, and a slow cleanup must not turn a finished check into one.
	checkTimedOut := ctx.Err() != nil
	cleanupCtx, cleanupCancel := context.WithTimeout(context.Background(), 10*time.Second)
	cleanupExit, cleanupErr := r.command(cleanupCtx, []string{"rm", "--force", result.JobID}, io.Discard)
	cleanupCancel()
	result.DurationMS = time.Since(started).Milliseconds()
	result.ExitCode = exit
	result.Output = output.data
	result.OutputTruncated = output.truncated
	sum := sha256.Sum256(output.data)
	result.OutputSHA256 = hex.EncodeToString(sum[:])
	switch {
	case cleanupErr != nil || cleanupExit != 0:
		result.Reason = "container cleanup was not confirmed"
	case checkTimedOut:
		result.Reason = "execution cancelled or exceeded wall-time limit"
	case runErr != nil || exit < 0 || exit == 75 || exit >= 125:
		result.Reason = "runtime or check preconditions unavailable"
	case output.truncated:
		result.Reason = "execution output exceeded its limit"
	case exit == 0:
		result.Status = Passed
	default:
		result.Status = Failed
	}
	return result
}

func (r *Runner) signature(result Result) string {
	result.Signature = ""
	raw, _ := json.Marshal(result)
	mac := hmac.New(sha256.New, r.key[:])
	_, _ = mac.Write(raw)
	return hex.EncodeToString(mac.Sum(nil))
}

// VerifyResult is the publication guard. A sandbox cannot mint a control-plane
// result or reuse evidence after the source head, snapshot or policy changed.
func (r *Runner) VerifyResult(result Result, snapshot Snapshot, check Check, currentHead string) error {
	if result.Status != Passed || result.ExitCode != 0 || result.OutputTruncated {
		return errors.New("selected checks did not complete successfully")
	}
	return r.VerifyReceipt(result, snapshot, check, currentHead)
}

// VerifyReceipt authenticates successful, failed and unavailable evidence alike.
func (r *Runner) VerifyReceipt(result Result, snapshot Snapshot, check Check, currentHead string) error {
	if result.Signature == "" || !hmac.Equal([]byte(result.Signature), []byte(r.signature(result))) {
		return errors.New("execution result authentication failed")
	}
	if result.Output != nil {
		digest := sha256.Sum256(result.Output)
		if result.OutputSHA256 != hex.EncodeToString(digest[:]) {
			return errors.New("execution output differs from its authenticated hash")
		}
	}
	if err := validateSnapshot(snapshot); err != nil {
		return err
	}
	if currentHead != snapshot.Head || result.Head != snapshot.Head || result.SnapshotSHA256 != snapshot.SHA256 || result.Check != check || result.JobID == "" {
		return errors.New("execution evidence is stale or belongs to another snapshot or check")
	}
	raw, _ := json.Marshal(struct {
		Policy Policy
		Check  Check
	}{r.policy, check})
	digest := sha256.Sum256(raw)
	if result.PolicySHA256 != hex.EncodeToString(digest[:]) {
		return errors.New("execution policy differs from the accepted result")
	}
	return nil
}
